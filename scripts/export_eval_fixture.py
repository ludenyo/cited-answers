"""Write tests/fixtures/eval_figures.sql from the full local database.

Run with: uv run --env-file .env python scripts/export_eval_fixture.py
Needs DATABASE_URL to point at a fully ingested database. CI never calls the World
Bank API; it loads this file instead.

What is exported: every figure the eval cases expect or require, plus the rest of each of
those series (every year), with their chunks and stored embeddings. The full series keep
wrong-year mistakes possible and make the newest year in the fixture the real newest year,
which the latest-year check depends on. The embeddings are copied, never recomputed.
"""

import re
import sys
from pathlib import Path
from typing import Any

import psycopg
import yaml

from cited_answers.db import connect

ROOT = Path(__file__).resolve().parents[1]
QUESTIONS = ROOT / "evals" / "questions.yaml"
OUTPUT = ROOT / "tests" / "fixtures" / "eval_figures.sql"
FIGURE_ID = re.compile(r"^(?P<country>[A-Z]{3}):(?P<indicator>[A-Z0-9.]+):\d{4}$")

FIGURE_COLUMNS = (
    "id, country_code, country_name, indicator_code, indicator_name, year, value, unit, source_url"
)


def expected_series(questions: list[dict[str, Any]]) -> list[tuple[str, str]]:
    """(country, indicator) for every series the eval cases need.

    That is every figure id they name, every latest-year pair, and every series listed under
    requires_series (for cases that need data but cite no figure id).
    """
    pairs: set[tuple[str, str]] = set()
    for q in questions:
        for figure_id in q["expect"].get("figure_ids", []):
            m = FIGURE_ID.match(figure_id)
            if not m:
                raise ValueError(f"{q['id']}: bad figure id {figure_id!r}")
            pairs.add((m["country"], m["indicator"]))
        for key in ("latest_year_check", "requires_series"):
            pairs |= {(c["country"], c["indicator"]) for c in q["expect"].get(key, [])}
    return sorted(pairs)


def literal(value: Any) -> str:
    """A SQL literal for the few types in the figures tables."""
    if value is None:
        return "NULL"
    if isinstance(value, int | float) or type(value).__name__ == "Decimal":
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def insert(table: str, columns: str, row: tuple[Any, ...]) -> str:
    values = ", ".join(literal(v) for v in row)
    return f"INSERT INTO {table} ({columns}) VALUES ({values}) ON CONFLICT DO NOTHING;"


def export(conn: psycopg.Connection, pairs: list[tuple[str, str]]) -> list[str]:
    lines = ["-- Generated by scripts/export_eval_fixture.py. Do not edit by hand."]
    figures = conn.execute(
        f"SELECT {FIGURE_COLUMNS} FROM figures "
        "WHERE (country_code, indicator_code) IN (SELECT * FROM unnest(%s::text[], %s::text[])) "
        "ORDER BY id",
        ([p[0] for p in pairs], [p[1] for p in pairs]),
    ).fetchall()
    ids = [row[0] for row in figures]
    lines += [insert("figures", FIGURE_COLUMNS, row) for row in figures]
    # embedding::text gives the '[0.1,0.2,...]' form pgvector accepts as input
    chunks = conn.execute(
        "SELECT figure_id, text, embedding::text FROM figure_chunks "
        "WHERE figure_id = ANY(%s) ORDER BY figure_id",
        (ids,),
    ).fetchall()
    lines += [insert("figure_chunks", "figure_id, text, embedding", row) for row in chunks]
    return lines


def main() -> None:
    questions = yaml.safe_load(QUESTIONS.read_text())["questions"]
    pairs = expected_series(questions)
    with connect() as conn:
        lines = export(conn, pairs)
    OUTPUT.write_text("\n".join(lines) + "\n")
    print(f"{len(pairs)} series, {(len(lines) - 1) // 2} figures -> {OUTPUT}", file=sys.stderr)


if __name__ == "__main__":
    main()
